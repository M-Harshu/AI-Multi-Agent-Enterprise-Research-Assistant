import type { Report } from "./report-types";

export function fallbackReport(company: string): Report {
  const c = company.trim() || "the company";

  return {
    company: c,
    ticker: "—",
    sector: "Enterprise Research",

    executiveSummary: `Unable to retrieve live analysis for ${c}. Please ensure the backend is running and try again.`,

    highlights: [
      "Backend unavailable",
      "Retry analysis",
      "Multi-Agent Research",
    ],

    research: [
      {
        claim: "Research could not be retrieved.",
        verdict: "unverified",
        note: "FastAPI backend did not return a response.",
      },
    ],

    bull: [
      {
        title: "Unavailable",
        detail: "Bullish analysis could not be generated.",
        weight: 50,
      },
    ],

    bear: [
      {
        title: "Unavailable",
        detail: "Bearish analysis could not be generated.",
        weight: 50,
      },
    ],

    judge: {
      verdict: "No Verdict",
      confidence: 0,
      rationale: "Backend unavailable.",
      bullScore: 50,
      bearScore: 50,
    },

    recommendation: {
      horizon: "Unknown",
      stance: "Retry",
      actions: [
        "Ensure backend is running",
        "Check company name",
        "Retry analysis",
      ],
    },

    conclusion: "Analysis could not be completed.",

    sources: [],
  };
}

export async function generateReport(company: string): Promise<Report> {
  try {
    const response = await fetch("http://localhost:8000/analyze", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        query: company,
      }),
    });

    if (!response.ok) {
  console.log("Status:", response.status);
  console.log("Response:", await response.text());
  return fallbackReport(company);
}

const text = await response.text();
console.log("Backend Response:", text);

const data = JSON.parse(text);

    const report: Report = {
      company,

      ticker: "—",

      sector: "Enterprise Research",

      executiveSummary: data.executive_summary,

      highlights: [
        "AI Multi-Agent Research",
        "Fact Checked",
        "Enterprise Intelligence",
      ],

      research: [
        {
          claim: data.verified_research,
          verdict: "verified",
          note: "Generated by Research + Fact Checker Agents",
        },
      ],

      bull: [
        {
          title: "Bullish Perspective",
          detail: data.bullish_perspective,
          weight: 70,
        },
      ],

      bear: [
        {
          title: "Bearish Perspective",
          detail: data.bearish_perspective,
          weight: 30,
        },
      ],

      judge: {
        verdict: data.final_verdict,
        confidence: 90,
        rationale: "Generated by Judge Agent",
        bullScore: 50,
        bearScore: 50,
      },

      recommendation: {
        horizon: "Long Term",
        stance: data.business_recommendation,
        actions: [
          "Review Executive Summary",
          "Compare Bull vs Bear",
          "Read Final Verdict",
        ],
      },

      conclusion: data.conclusion,

      sources: (data.sources || []).map((source: any) => ({
        title: source.title,
        domain: source.source,
        url: source.url,
        snippet: `${source.agent} • Confidence: ${source.confidence}`,
      })),
    };

    return report;
  } catch (error) {
  console.error("REAL ERROR:", error);
  throw error;
}
}